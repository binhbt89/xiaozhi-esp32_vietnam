lines.extend([
    "};",
    "",
    "static constexpr size_t kMochiHudIconAssetCount =",
    "    sizeof(kMochiHudIconAssets) / sizeof(kMochiHudIconAssets[0]);",
    "static_assert(kMochiHudIconAssetCount == 5);",
    "",
])

OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"Generated {OUT} ({OUT.stat().st_size} bytes)")
