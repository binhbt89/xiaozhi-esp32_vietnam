ORDER = ["fullness", "energy", "mood", "friendship", "coin"]
SOURCE_SIZE = 16
TARGET_SIZE = 20


def scale_rows(rows):
    if len(rows) != SOURCE_SIZE or any(len(row) != SOURCE_SIZE for row in rows):
        raise SystemExit("Every source icon must be exactly 16x16")
    out = []
    for y in range(TARGET_SIZE):
        sy = min(SOURCE_SIZE - 1, (y * SOURCE_SIZE) // TARGET_SIZE)
        row = []
        for x in range(TARGET_SIZE):
            sx = min(SOURCE_SIZE - 1, (x * SOURCE_SIZE) // TARGET_SIZE)
            row.append(rows[sy][sx])
        out.append("".join(row))
    return out


def bytes_for(rows):
    rows = scale_rows(rows)
    data = []
    for row in rows:
        for key in row:
            if key not in PALETTE:
                raise SystemExit(f"Unknown palette key: {key!r}")
            r, g, b, a = PALETTE[key]
            data.extend((b, g, r, a))
    return data


