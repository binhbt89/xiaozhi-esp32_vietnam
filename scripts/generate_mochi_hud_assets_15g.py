        "};",
        f"static const lv_image_dsc_t {dsc_name} = {{",
        "    {LV_IMAGE_HEADER_MAGIC, LV_COLOR_FORMAT_ARGB8888, 0, 16, 16, 64, 0},",
        f"    sizeof({map_name}),",
        f"    {map_name},",
