ORDER = ["fullness", "energy", "mood", "friendship", "coin"]


def bytes_for(rows):
    if len(rows) != 16 or any(len(row) != 16 for row in rows):
        raise SystemExit("Every 15G icon must be exactly 16x16")
    data = []
    for row in rows:
        for key in row:
            if key not in PALETTE:
                raise SystemExit(f"Unknown palette key: {key!r}")
            r, g, b, a = PALETTE[key]
            # LVGL ARGB8888 is represented by lv_color32_t in memory as BGRA.
            data.extend((b, g, r, a))
    return data


